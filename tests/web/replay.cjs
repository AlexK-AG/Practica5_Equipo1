/* Actual Godot telemetry -> private SQLite -> local HTTP -> browser. */
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs/promises');
const {createHash}=require('node:crypto');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.SECTOR07_PLAYWRIGHT_MODULE||'playwright');
const root=path.resolve(__dirname,'../..');
async function main(){
  const {createServer,readDashboard}=await import(pathToFileURL(path.join(root,'web/server.mjs')));
  const {readReplay}=await import(pathToFileURL(path.join(root,'web/replay-data.mjs')));
  const file=path.join(root,'.godot/replay-private.sqlite');
  const hash=async()=>createHash('sha256').update(await fs.readFile(file)).digest('hex');
  const before=await hash(),data=readDashboard(file),run=data.runs.find(row=>row.level===10),replay=readReplay(file,run.id);
  assert.equal(data.databaseSchemaVersion,4);assert.equal(run.hasReplay,true);assert.deepEqual(run.loadout,['pistol']);
  assert.equal(replay.available,true);assert.equal(replay.frames.at(-1).t,3);
  assert(replay.metadata.map.floors.length>0);assert(replay.frames[0].enemies.length>0);
  assert.equal(readReplay(file,'missing-attempt').available,false);
  const server=createServer({databasePath:file});let browser;
  try{
    await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
    const base=`http://127.0.0.1:${server.address().port}`;
    assert.equal((await fetch(base+'/api/replay?run='+run.id)).status,200);
    assert.equal((await fetch(base+'/api/replay')).status,503);
    assert.equal((await fetch(base+'/replay-data.mjs')).status,404);
    browser=await chromium.launch({channel:'msedge',headless:true});
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(base+'/#overview');await page.getByText('Datos conectados',{exact:true}).waitFor();
    await page.locator('[data-analytics-root]').waitFor();
    await page.locator('nav [data-page="replays"]').click();
    await page.getByRole('heading',{name:'Partidas y recorridos',exact:true}).waitFor();
    await page.locator('#level-filter').selectOption('10');
    assert.equal(await page.locator('tbody tr').count(),1);
    await page.getByLabel('Ver partida de Replay test, nivel 10').click();
    await page.locator('.replay-map canvas').waitFor();
    assert.deepEqual(await page.evaluate(()=>S07_REPLAY.interpolate([0,0],[20,20],.5)),[0,0],'Teleport does not invent intermediate movement');
    assert.deepEqual(await page.evaluate(()=>S07_REPLAY.interpolate([0,0],[2,4],.5)),[1,2],'Normal movement interpolates smoothly');
    assert.match(await page.locator('#detail-content').innerText(),/Pistola/);
    assert(await page.locator('[data-replay-enemies] li').count()>0);
    const seek=page.getByLabel('Momento de la reproducción');
    await page.getByRole('button',{name:'▶ Reproducir',exact:true}).click();
    await page.waitForFunction(()=>Number(document.querySelector('[data-replay-host] input').value)>.2);
    await page.getByRole('button',{name:'Ⅱ Pausar',exact:true}).click();
    const paused=await seek.inputValue();await page.waitForTimeout(150);assert.equal(await seek.inputValue(),paused);
    await page.getByLabel('Velocidad de reproducción').selectOption('4');
    await seek.focus();await seek.press('End');assert.equal(Number(await seek.inputValue()),3);
    await page.getByRole('button',{name:'↺ Reiniciar',exact:true}).click();assert.equal(Number(await seek.inputValue()),0);
    const shots=path.join(root,'.godot/test-results/capturas');await fs.mkdir(shots,{recursive:true});
    await page.screenshot({path:path.join(shots,'replay-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(100);
    assert(await page.locator('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth+2),'Mobile detail does not overflow');
    await page.screenshot({path:path.join(shots,'replay-mobile.png'),fullPage:true});
    await page.getByLabel('Cerrar detalle').click();
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('nav [data-page="players"]').click();
    await page.locator('[data-profile]').first().click();
    assert.match(await page.locator('#detail-content').innerText(),/favorita/i);
    await page.getByLabel('Cerrar detalle').click();
    await page.locator('nav [data-page="replays"]').click();
    await page.locator('#level-filter').selectOption('1');
    await page.getByLabel('Ver partida de Replay test, nivel 1',{exact:true}).click();
    await page.getByRole('heading',{name:'Sin recorrido registrado'}).waitFor();
    assert.deepEqual(errors,[]);
    assert.equal(await hash(),before,'Web only reads the game database');
    console.log('REPLAY WEB PASS: Godot data, map, subtype labels, transport, seeking, equipment, favorite, old attempts, mobile, read-only');
  }finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
